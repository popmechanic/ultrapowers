/**
 * fleet/tests/_readiness_helpers.mjs — the fold-order sim's machinery.
 *
 * Underscore-prefixed so test_fleet_suite.py's `test_*.mjs` glob does not run
 * it as a test of its own; `fleet/tests/test_readiness_fold_order.mjs` is the
 * sim, and `fleet/tests/test_readiness_fold_order_exam.mjs` the exam that
 * grades it.
 *
 * The one export the plan pins is `runSet(spec)`. Everything else here exists
 * to build a `spec`: the fixture corpus, the committed reply roots, the
 * real-join sets under `fleet/tests/fixtures/readiness/`.
 *
 * What a set is
 * -------------
 * A set is a BASE commit in a scratch repo plus N task patches taken against
 * it (`git diff --binary --full-index --no-renames <BASE>`, exactly what
 * `corpuslib._capture_patch` writes). `runSet` folds it twice over:
 *
 *   simultaneously  one `fold` over all N patches, one `materialize`;
 *   sequentially    for every order the kernel's own `sampled_orders(N)`
 *                   returns, one step per task — `adopted` (the diff from
 *                   BASE to the head built so far) alongside the next task's
 *                   patch, folded against BASE and materialized onto that
 *                   head.
 *
 * and returns both answers. The claim under measurement is that every order's
 * candidate `^{tree}` equals the simultaneous candidate's.
 *
 * Three facts about the kernel this file is built around, each paid for by
 * hand before it was written:
 *
 *   - `fold` exits 2 when `<run-dir>/frontier/wave-<n>/fold_log.jsonl` already
 *     exists, so every step gets a run directory of its own.
 *   - a set's `commutes` declaration has to be carried onto the `adopted`
 *     pseudo-task at every step where an already-adopted task declared that
 *     path. Corpus wave 2 (two appends at one anchor, both declared
 *     commutative) narrates a `lines` conflict on `c.txt` at its second step
 *     and falls back in `materialize` without it.
 *   - `resolve` takes no `--base`; it reads the base out of the fold log.
 *
 * Replies are never generated by the sim. A conflict's reply is a committed
 * file under a reply root laid out the way a real-join fixture lays it out —
 * `<root>/<path, "/" as "__">/h<N>.txt` — and `runSet` copies the bytes of
 * exactly the hunk files one conflict names into the dir it hands `resolve`.
 * A reply is keyed by `(set, path, hunk id)` and never by which side the
 * narration happened to label `frontier`: wave 3's conflict shows `3b` on the
 * right simultaneously and on the left in the order that adopts it first, and
 * the resolved region is one file either way.
 *
 * `spec.replies` also accepts a function, for a caller that wants to build a
 * divergence rather than commit one: it is called per hunk with
 * `{path, hunk, mode, order, step}` and returns that hunk's reply text. The sim
 * itself never passes one — every set it runs answers from a committed root, so
 * the constraint that no reply is produced at test time holds where it is
 * claimed. The form exists because the negative control IS a set whose reply is
 * not a function of `(set, path, hunk)` alone, and an examiner building its own
 * control should not have to commit two texts to do it.
 *
 * Soft edges: a task may carry a `base` of its own — the head it was
 * re-captured against, rather than the set's BASE. Tasks are grouped into
 * layers by that recorded base (the set's own BASE first, then each soft base
 * in the order it first appears), and a layer folds against its own base and
 * materializes onto the head the layer before it built. A recorded base already
 * carries the work it was taken over, so a soft-edge step folds its task alone,
 * with no `adopted` pseudo-task beside it. Sequentially, a sampled order is
 * stabilized to respect that layering — a soft edge slides to just after the
 * last task of every earlier layer — which reorders an order, never drops one.
 */

