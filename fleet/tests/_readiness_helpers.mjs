// ── process plumbing ──────────────────────────────────────────────────────

/**
 * Run `file argv`, returning `{ status, stdout, stderr }`. Never throws on a
 * non-zero exit: the kernel says 0 at a stop, 2 at a refusal and 3 at a
 * fallback, and every one of those carries a reply on stdout the caller reads.
 */
export function sh (file, argv, { cwd = REPO_ROOT, buffer = false } = {}) {
  try {
    const stdout = execFileSync(file, argv, {
      cwd, env: ENV, encoding: buffer ? 'buffer' : 'utf8',
      maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'],
    })
    return { status: 0, stdout, stderr: buffer ? Buffer.alloc(0) : '' }
  } catch (e) {
    if (e.status === undefined) throw e
    return { status: e.status, stdout: e.stdout, stderr: e.stderr }
  }
}

/** `git -C cwd argv…`, trimmed; throws with git's own stderr on failure. */
export function git (argv, cwd) {
  const r = sh('git', ['-C', cwd, ...argv])
  if (r.status !== 0) {
    throw new Error('git ' + argv.join(' ') + ' in ' + cwd + ' failed: ' + String(r.stderr || ''))
  }
  return String(r.stdout).trim()
}

/** `git -C cwd argv…` with binary stdout kept as bytes. */
function gitBytes (argv, cwd) {
  const r = sh('git', ['-C', cwd, ...argv], { buffer: true })
  if (r.status !== 0) {
    throw new Error('git ' + argv.join(' ') + ' in ' + cwd + ' failed: ' + String(r.stderr || ''))
  }
  return r.stdout
}

/** The `^{tree}` sha of a commit — the thing every assertion here compares. */
export const treeOf = (repo, sha) => git(['rev-parse', sha + '^{tree}'], repo)

/** `python3 -c <src> args…`; throws with the interpreter's stderr. */
function py (src, args = []) {
  const r = sh('python3', ['-c', src, ...args])
  if (r.status !== 0) {
    throw new Error('python3 -c failed (' + r.status + '): ' + String(r.stderr || ''))
  }
  return String(r.stdout)
}

export const sha256OfBytes = (bytes) => createHash('sha256').update(bytes).digest('hex')
export const sha256OfFile = (file) => sha256OfBytes(fs.readFileSync(file))

/** A fresh scratch directory under the temp root the sim was handed. */
export const mkTemp = (prefix) => fs.mkdtempSync(path.join(os.tmpdir(), prefix))

// ── the kernel's own order sampler ────────────────────────────────────────

const ORDERS_SRC = [
  'import sys, json',
  'sys.path.insert(0, sys.argv[1])',
  'from frontier_fold import sampled_orders',
  'print(json.dumps(sampled_orders(int(sys.argv[2]))))',
].join('\n')

const orderCache = new Map()

/**
 * `sampled_orders(n)` read out of the kernel rather than reimplemented — all
 * n! for n <= 4, the identity plus 19 seeded shuffles above. The sim may never
 * sample fewer orders than this returns.
 */
export function sampledOrders (n) {
  if (!orderCache.has(n)) orderCache.set(n, JSON.parse(py(ORDERS_SRC, [KERNEL_DIR, String(n)])))
  return orderCache.get(n).map((o) => o.slice())
}

